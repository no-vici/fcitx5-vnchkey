"""
Configuration Manager for vnchKey.
Reads and writes ~/.config/fcitx5/conf/vnchkey.conf, macro tables, and dictionaries.
"""

import os
import subprocess


class ConfigManager:
    def __init__(self):
        self.config_dir = os.path.expanduser("~/.config/fcitx5/conf")
        os.makedirs(self.config_dir, exist_ok=True)
        self.conf_path = os.path.join(self.config_dir, "vnchkey.conf")
        self.macro_path = os.path.join(self.config_dir, "vnchkey-macro-table.conf")
        self.dict_path = os.path.join(self.config_dir, "vnchkey-dictionary.conf")

        self.default_config = {
            "InputMethod": "Auto",  # Auto, Telex, VNI
            "Mode": "Native Fcitx5 (Direct Commit)",  # Native, Uinput (Smooth)
            "OutputCharset": "Unicode",
            "ModernStyle": "True",  # True: oà, uý; False: hòa, úy
            "SmartHorn": "True",    # True: auto horn on duoc -> được, nuoc -> nước
            "AutoRestoreEnglish": "True",  # GoNhanh innovation
            "SmartCasing": "True",  # XKey innovation
            "EnableMacro": "True",
            "TypeW2U": "Non-Start",  # Non-Start, Always, Disabled
        }

    def load_config(self) -> dict:
        config = dict(self.default_config)
        if not os.path.exists(self.conf_path):
            return config

        try:
            with open(self.conf_path, "r", encoding="utf-8") as f:
                for line in f:
                    line = line.strip()
                    if not line or line.startswith("#"):
                        continue
                    if "=" in line:
                        k, v = line.split("=", 1)
                        k = k.strip()
                        v = v.strip().strip("\"'")
                        config[k] = v
        except Exception as e:
            print(f"Error reading config: {e}")
        return config

    def save_config(self, config: dict):
        try:
            with open(self.conf_path, "w", encoding="utf-8") as f:
                f.write("# vnchKey Configuration File\n")
                f.write("# Generated by vnchKey Settings\n\n")
                for k, v in config.items():
                    f.write(f"{k}={v}\n")
            self.reload_fcitx5()
        except Exception as e:
            print(f"Error saving config: {e}")

    def load_macros(self) -> list:
        macros = []
        if not os.path.exists(self.macro_path):
            # Default helpful Vietnamese abbreviations
            return [
                ("vn", "Việt Nam"),
                ("dc", "được"),
                ("ko", "không"),
                ("ng", "người"),
                ("hn", "hôm nay"),
            ]

        try:
            with open(self.macro_path, "r", encoding="utf-8") as f:
                for line in f:
                    line = line.strip()
                    if not line or line.startswith("#"):
                        continue
                    if "=" in line:
                        k, v = line.split("=", 1)
                        macros.append((k.strip(), v.strip()))
        except Exception as e:
            print(f"Error loading macros: {e}")
        return macros

    def save_macros(self, macros: list):
        try:
            with open(self.macro_path, "w", encoding="utf-8") as f:
                f.write("# vnchKey Macro Replacement Table\n")
                for k, v in macros:
                    if k.strip():
                        f.write(f"{k.strip()}={v.strip()}\n")
            self.reload_fcitx5()
        except Exception as e:
            print(f"Error saving macros: {e}")

    def load_dictionary(self) -> list:
        words = []
        if not os.path.exists(self.dict_path):
            return words

        try:
            with open(self.dict_path, "r", encoding="utf-8") as f:
                for line in f:
                    line = line.strip()
                    if line and not line.startswith("#"):
                        words.append(line)
        except Exception as e:
            print(f"Error loading dictionary: {e}")
        return words

    def save_dictionary(self, words: list):
        try:
            with open(self.dict_path, "w", encoding="utf-8") as f:
                f.write("# vnchKey Custom User Words Dictionary\n")
                for word in words:
                    if word.strip():
                        f.write(f"{word.strip()}\n")
            self.reload_fcitx5()
        except Exception as e:
            print(f"Error saving dictionary: {e}")

    def reload_fcitx5(self):
        """Notify Fcitx5 to reload configurations."""
        try:
            # 1. Try D-Bus notification
            subprocess.run(
                [
                    "gdbus", "call", "--session",
                    "--dest", "org.fcitx.Fcitx5",
                    "--object-path", "/controller",
                    "--method", "org.fcitx.Fcitx.Controller1.ReloadAddonConfig",
                    "vnchkey"
                ],
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL,
                timeout=1,
            )
        except Exception:
            pass
