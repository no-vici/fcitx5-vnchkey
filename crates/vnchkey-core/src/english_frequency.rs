/// Strong English threshold used as a conservative signal.
pub const STRONG_EN_MIN: u8 = 150;

/// Lookup EN/VN frequency scores for a lowercase ASCII word.
/// Returns None when the word is not in the table.
pub fn scores(word: &str) -> Option<(u8, u8)> {
    let bytes = word.as_bytes();
    let idx = WORD_SCORES.binary_search_by(|(w, _, _)| w.as_bytes().cmp(bytes)).ok()?;
    let (_, en, vn) = WORD_SCORES[idx];
    Some((en, vn))
}

